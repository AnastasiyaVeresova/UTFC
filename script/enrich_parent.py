    log(f"Найдено родительских файлов: {len(parent_files)}")

    not_found = []
    updated = 0

    for variant in variants:
        base_name = variant.get("base_name", "")
        mapped_name = find_mapped_name(base_name)
        log(f"Ищем для base_name: {base_name} -> mapped: {mapped_name}")

        parent_file_path, parent_data = find_parent_file(mapped_name, parent_files)

        if parent_file_path:
            updated_fields = enrich_parent(parent_data, variant)
            if updated_fields:
                updated += 1
                log(f"Обновлен {parent_file_path}: {', '.join(updated_fields)}")
                with open(parent_file_path, "w", encoding="utf-8") as f:
                    json.dump(parent_data, f, ensure_ascii=False, indent=4)
        else:
            not_found.append(base_name)

    log(f"\n=== Итоги ===")
    log(f"Обновлено родительских файлов: {updated}")
    log(f"Не найдено соответствий: {len(set(not_found))}")
    if not_found:
        log("Список не найденных base_name:")
