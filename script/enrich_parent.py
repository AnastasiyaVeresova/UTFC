def normalize_name_for_mapping(name):
    if not name:
        return ""
    # Убираем только лишние слова, но сохраняем характеристики
    words_to_remove = [
        "кресло", "стул", "табурет", "производства", "компании", "utfc", "utf-c", "utf c", "производства utfc",
        "производства utf-c", "производства utf c", "производства utfc мебель",
    ]
    name_lower = name.lower()
    for word in words_to_remove:
        name_lower = name_lower.replace(word, "")
    # Убираем лишние пробелы
    name_lower = " ".join(name_lower.split())
    return name_lower.strip()

